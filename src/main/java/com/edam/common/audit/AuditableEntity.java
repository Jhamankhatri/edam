package com.edam.common.audit;

import java.time.Instant;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.Version;

import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

import org.springframework.data.annotation.CreatedBy;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedBy;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

/**
 * Audit stamps, a UUID primary key and optimistic locking for every mutable EDAM entity.
 *
 * <h2>Why UUIDv7 rather than a sequence or a random UUID</h2>
 * <ul>
 *   <li><strong>Sequence:</strong> reveals record counts and creation order to anyone who sees an id
 *       in a URL, and makes ids guessable.</li>
 *   <li><strong>Random UUIDv4:</strong> solves both, but destroys B-tree locality — every insert lands
 *       at a random page, and the primary key index on a multi-million-row {@code audit_events} or
 *       {@code expense_requests} table becomes fragmented and slow.</li>
 *   <li><strong>UUIDv7:</strong> time-ordered prefix, random suffix. Inserts stay at the right edge of
 *       the index (like a sequence), ids are still unguessable, and the id can be generated by the
 *       database ({@code uuidv7()} in migration V5+) or in Java without coordination.</li>
 * </ul>
 * The id is never generated by Hibernate. This is deliberate: a strategy of
 * {@code GenerationType.UUID} would emit a v4 UUID, silently losing the ordering benefit that is the
 * whole reason for choosing v7. {@code @Generated(event = INSERT)} lets PostgreSQL's default supply
 * the value and reads it back after the insert.
 *
 * <h2>Note the absence of tenant columns</h2>
 * An earlier revision carried an {@code institution_id} discriminator because the tenant-isolation
 * model was undecided. The requirement now states the model: one installation, one bank, with
 * {@code organization_profile} explicitly "not a multi-bank registry". Access is narrowed per user by
 * organizational data scopes instead, so no inherited discriminator exists to forget to filter on.
 *
 * <h2>Timestamps</h2>
 * Always UTC ({@link Instant}). Presentation-time zone is a client concern.
 */
@MappedSuperclass
@EntityListeners(AuditingEntityListener.class)
public abstract class AuditableEntity {

	@Id
	@Generated(event = EventType.INSERT)
	@Column(name = "id", nullable = false, updatable = false)
	private UUID id;

	@CreatedDate
	@Column(name = "created_at", nullable = false, updatable = false)
	private Instant createdAt;

	@CreatedBy
	@Column(name = "created_by", updatable = false, length = 100)
	private String createdBy;

	@LastModifiedDate
	@Column(name = "updated_at", nullable = false)
	private Instant updatedAt;

	@LastModifiedBy
	@Column(name = "updated_by", length = 100)
	private String updatedBy;

	/**
	 * Optimistic locking. Required by approval actions: two approvers acting on the same task must
	 * not both succeed, and the second must be told to reload rather than silently overwriting.
	 */
	@Version
	@Column(name = "version", nullable = false)
	private long version;

	public UUID getId() {
		return this.id;
	}

	public Instant getCreatedAt() {
		return this.createdAt;
	}

	public String getCreatedBy() {
		return this.createdBy;
	}

	public Instant getUpdatedAt() {
		return this.updatedAt;
	}

	public String getUpdatedBy() {
		return this.updatedBy;
	}

	public long getVersion() {
		return this.version;
	}

}
