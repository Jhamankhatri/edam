-- ============================================================================
-- EDAM Foundation Schema (Phase 1 Only)
-- Establishes multi-institution identity, branding, configuration, multi-tenant
-- user memberships, permissions, and immutable audit trail tables.
-- Business tables (OPEX, CAPEX, workflows, committees) are intentionally deferred
-- until BRD open decisions (OD-01 through OD-22) are approved.
-- ============================================================================

CREATE TABLE institutions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  VARCHAR(32)  NOT NULL,
    name                  VARCHAR(150) NOT NULL,
    short_name            VARCHAR(50)  NOT NULL,
    legal_name            VARCHAR(200),
    status                VARCHAR(20)  NOT NULL,
    default_currency_code VARCHAR(3)   NOT NULL,
    locale                VARCHAR(20)  NOT NULL,
    time_zone             VARCHAR(64)  NOT NULL,
    created_at            TIMESTAMPTZ  NOT NULL,
    updated_at            TIMESTAMPTZ  NOT NULL,
    created_by            VARCHAR(120) NOT NULL,
    updated_by            VARCHAR(120) NOT NULL,
    version               BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_institutions_code UNIQUE (code),
    CONSTRAINT chk_institutions_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);

CREATE INDEX idx_institutions_lower_code_status
    ON institutions (LOWER(code), status);

CREATE TABLE institution_branding (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id  BIGINT       NOT NULL,
    product_title   VARCHAR(120) NOT NULL,
    logo_path       VARCHAR(255) NOT NULL,
    favicon_path    VARCHAR(255) NOT NULL,
    primary_color   VARCHAR(7)   NOT NULL,
    secondary_color VARCHAR(7)   NOT NULL,
    accent_color    VARCHAR(7)   NOT NULL,
    theme_mode      VARCHAR(16)  NOT NULL,
    footer_text     VARCHAR(250) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    created_by      VARCHAR(120) NOT NULL,
    updated_by      VARCHAR(120) NOT NULL,
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_institution_branding_inst FOREIGN KEY (institution_id) REFERENCES institutions (id) ON DELETE RESTRICT,
    CONSTRAINT uk_institution_branding_institution UNIQUE (institution_id),
    CONSTRAINT chk_institution_branding_theme CHECK (theme_mode IN ('LIGHT', 'DARK'))
);

CREATE TABLE institution_settings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT       NOT NULL,
    setting_key    VARCHAR(100) NOT NULL,
    setting_value  TEXT         NOT NULL,
    value_type     VARCHAR(30)  NOT NULL,
    description    VARCHAR(300),
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(120) NOT NULL,
    updated_by     VARCHAR(120) NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_institution_settings_inst FOREIGN KEY (institution_id) REFERENCES institutions (id) ON DELETE RESTRICT,
    CONSTRAINT uk_institution_settings_inst_key UNIQUE (institution_id, setting_key)
);

CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username              VARCHAR(100) NOT NULL,
    email                 VARCHAR(200) NOT NULL,
    display_name          VARCHAR(150) NOT NULL,
    password_hash         VARCHAR(255),
    auth_provider         VARCHAR(40)  NOT NULL DEFAULT 'LOCAL',
    external_subject_id   VARCHAR(200),
    status                VARCHAR(20)  NOT NULL,
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMPTZ,
    created_at            TIMESTAMPTZ  NOT NULL,
    updated_at            TIMESTAMPTZ  NOT NULL,
    created_by            VARCHAR(120) NOT NULL,
    updated_by            VARCHAR(120) NOT NULL,
    version               BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT chk_users_status CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED'))
);

CREATE INDEX idx_users_lower_username ON users (LOWER(username));
CREATE INDEX idx_users_status ON users (status);

CREATE TABLE permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(100) NOT NULL,
    module_code VARCHAR(50)  NOT NULL,
    description VARCHAR(255) NOT NULL,
    CONSTRAINT uk_permissions_code UNIQUE (code)
);

CREATE TABLE roles (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT,
    code           VARCHAR(64)  NOT NULL,
    name           VARCHAR(120) NOT NULL,
    description    VARCHAR(300),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(120) NOT NULL,
    updated_by     VARCHAR(120) NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_roles_institution FOREIGN KEY (institution_id) REFERENCES institutions (id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uk_roles_institution_code
    ON roles (institution_id, code)
    WHERE institution_id IS NOT NULL;

CREATE UNIQUE INDEX uk_roles_platform_code
    ON roles (code)
    WHERE institution_id IS NULL;

CREATE TABLE role_permissions (
    role_id       BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_perm FOREIGN KEY (permission_id) REFERENCES permissions (id) ON DELETE RESTRICT
);

CREATE TABLE user_institution_memberships (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    institution_id  BIGINT       NOT NULL,
    employee_code   VARCHAR(64),
    department_code VARCHAR(64),
    is_default      BOOLEAN      NOT NULL DEFAULT FALSE,
    status          VARCHAR(20)  NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    created_by      VARCHAR(120) NOT NULL,
    updated_by      VARCHAR(120) NOT NULL,
    version         BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_uim_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_uim_institution FOREIGN KEY (institution_id) REFERENCES institutions (id) ON DELETE RESTRICT,
    CONSTRAINT uk_user_inst_membership UNIQUE (user_id, institution_id),
    CONSTRAINT chk_membership_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'REVOKED'))
);

CREATE INDEX idx_uim_user_status ON user_institution_memberships (user_id, status);
CREATE INDEX idx_uim_inst_status ON user_institution_memberships (institution_id, status);

CREATE TABLE user_institution_roles (
    membership_id BIGINT NOT NULL,
    role_id       BIGINT NOT NULL,
    PRIMARY KEY (membership_id, role_id),
    CONSTRAINT fk_uir_membership FOREIGN KEY (membership_id) REFERENCES user_institution_memberships (id) ON DELETE CASCADE,
    CONSTRAINT fk_uir_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT
);

CREATE TABLE audit_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id  BIGINT,
    correlation_id  VARCHAR(64)  NOT NULL,
    actor_username  VARCHAR(120) NOT NULL,
    actor_user_id   BIGINT,
    action_type     VARCHAR(64)  NOT NULL,
    module_name     VARCHAR(64)  NOT NULL,
    entity_type     VARCHAR(100) NOT NULL,
    entity_id       VARCHAR(100),
    summary         VARCHAR(500) NOT NULL,
    old_values_json TEXT,
    new_values_json TEXT,
    source_ip       VARCHAR(64),
    occurred_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_audit_events_institution FOREIGN KEY (institution_id) REFERENCES institutions (id) ON DELETE RESTRICT
);

CREATE INDEX idx_audit_events_inst_time ON audit_events (institution_id, occurred_at DESC);
CREATE INDEX idx_audit_events_correlation ON audit_events (correlation_id);
CREATE INDEX idx_audit_events_entity ON audit_events (entity_type, entity_id);
