-- =====================================================================================
-- EDAM — configuration plane and audit (V3)
--
-- Scope: institution settings, the configuration plane (categories, delegation matrix,
-- currencies, limits, recommending authorities, Expense Committee), roles/permissions and
-- the append-only audit trail.
--
-- Conventions (see docs/DATABASE_GUIDELINES.md):
--   * snake_case, singular table names.
--   * Every institution-owned table carries institution_id NOT NULL and a composite index
--     that LEADS with it, so a tenant query is the natural query and a cross-tenant scan is
--     visibly unusual in review.
--   * Money NUMERIC(19,2); rates NUMERIC(19,4) as the BRD requires "up to four decimals".
--   * Audit columns created_at/created_by/updated_at/updated_by/version on mutable rows.
--
-- Tenant isolation model: shared schema + discriminator. BRD OD-23 is still open, so this is
-- a provisional, reversible decision (ADR-0002). The discriminator is enforced by
-- application code plus these NOT NULL constraints and indexes; it is documented, not
-- assumed.
-- =====================================================================================

-- -------------------------------------------------------------------------------------
-- Institution: settings and feature flags (BRD INS-01..04)
--
-- The foundation stored branding directly on institution. Institution-level SETTINGS that
-- must be versioned and exported separately live in their own table so a theme/feature
-- change is auditable as a configuration change rather than as a column update.
-- -------------------------------------------------------------------------------------

ALTER TABLE institution
    ADD COLUMN display_name VARCHAR(200),
    ADD COLUMN support_email VARCHAR(200),
    ADD COLUMN date_format VARCHAR(40) NOT NULL DEFAULT 'dd MMM yyyy',
    ADD COLUMN number_format VARCHAR(40) NOT NULL DEFAULT '#,##0.00',
    ADD COLUMN status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE';

ALTER TABLE institution
    ADD CONSTRAINT ck_institution_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DEACTIVATED'));

COMMENT ON COLUMN institution.status IS
    'Lifecycle state (INS-01). DEACTIVATED institutions retain their data for audit but cannot be selected.';

-- -------------------------------------------------------------------------------------
-- Permission catalogue and institution-scoped roles (BRD IAM-01, IAM-02, §23)
--
-- Before this migration the only permissions in the product were seven strings in a Java
-- class and roles were free text on an in-memory fixture, which made institution-scoped
-- authorization impossible. The tables below are the runtime authority.
-- -------------------------------------------------------------------------------------

CREATE TABLE permission_definition (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(80) NOT NULL,
    module        VARCHAR(40) NOT NULL,
    action        VARCHAR(40) NOT NULL,
    description   VARCHAR(300),
    built_in      BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL,
    created_by    VARCHAR(64) NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,
    updated_by    VARCHAR(64) NOT NULL,
    version       BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_permission_code UNIQUE (code),
    CONSTRAINT ck_permission_code_format CHECK (code ~ '^[a-z][a-z0-9-]*:[a-z][a-z0-9-]*$')
);

COMMENT ON TABLE permission_definition IS
    'Catalogue of machine-readable permission codes (IAM-02). Codes are a public contract and are never renamed or reused.';

CREATE TABLE role (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT      NOT NULL REFERENCES institution (id),
    code           VARCHAR(64) NOT NULL,
    name           VARCHAR(120) NOT NULL,
    description    VARCHAR(300),
    system_role    BOOLEAN     NOT NULL DEFAULT FALSE,
    active         BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL,
    created_by     VARCHAR(64) NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    updated_by     VARCHAR(64) NOT NULL,
    version        BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_role_code_format CHECK (code ~ '^[A-Z][A-Z0-9_]{1,63}$')
);

-- Active role codes are unique per institution; a deactivated role may keep its code so its
-- historical audit trail stays meaningful.
CREATE UNIQUE INDEX uk_role_institution_code_active ON role (institution_id, code) WHERE active;
CREATE INDEX ix_role_institution ON role (institution_id);

CREATE TABLE role_permission (
    role_id       BIGINT NOT NULL REFERENCES role (id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permission_definition (id),
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE user_membership (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id    BIGINT      NOT NULL REFERENCES institution (id),
    employee_id       VARCHAR(64) NOT NULL,
    username          VARCHAR(64) NOT NULL,
    display_name      VARCHAR(200),
    email             VARCHAR(200),
    department_code   VARCHAR(64),
    branch_code       VARCHAR(64),
    designation       VARCHAR(120),
    active            BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMPTZ NOT NULL,
    created_by        VARCHAR(64) NOT NULL,
    updated_at        TIMESTAMPTZ NOT NULL,
    updated_by        VARCHAR(64) NOT NULL,
    version           BIGINT      NOT NULL DEFAULT 0
);

-- A user may belong to several institutions (IAM-04); membership is the pair, not the user.
CREATE UNIQUE INDEX uk_user_membership_institution_employee
    ON user_membership (institution_id, employee_id);
CREATE INDEX ix_user_membership_username ON user_membership (username);

CREATE TABLE user_membership_role (
    membership_id BIGINT NOT NULL REFERENCES user_membership (id) ON DELETE CASCADE,
    role_id       BIGINT NOT NULL REFERENCES role (id),
    PRIMARY KEY (membership_id, role_id)
);

