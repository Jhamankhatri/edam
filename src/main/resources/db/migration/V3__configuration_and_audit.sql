CREATE TABLE expense_category (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT       NOT NULL REFERENCES institution (id),
    name           VARCHAR(120) NOT NULL,
    description    VARCHAR(500),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    display_order  INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(64)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    updated_by     VARCHAR(64)  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0
);

-- "Active category names are unique" (BRD §8.6). A partial unique index is required rather
-- than a table constraint because deactivated categories may share a name with a new active
-- one, and a service-level check alone would race under concurrent administration.
CREATE UNIQUE INDEX uk_expense_category_active_name
    ON expense_category (institution_id, lower(name)) WHERE active;
CREATE INDEX ix_expense_category_institution ON expense_category (institution_id, active);

CREATE TABLE expense_subcategory (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT       NOT NULL REFERENCES institution (id),
    category_id    BIGINT       NOT NULL REFERENCES expense_category (id),
    name           VARCHAR(120) NOT NULL,
    description    VARCHAR(500),
