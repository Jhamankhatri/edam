-- Administrator: every built-in permission in its own institution.
INSERT INTO role_permission (role_id, permission_id)
SELECT r.id, p.id
FROM role r
CROSS JOIN permission_definition p
WHERE r.code = 'INSTITUTION_ADMINISTRATOR' AND r.system_role;

-- Requester: create and track own requests, upload documents.
INSERT INTO role_permission (role_id, permission_id)
SELECT r.id, p.id
FROM role r
JOIN permission_definition p
    ON p.code IN ('request:view-own', 'request:create', 'request:edit-returned', 'request:submit',
                  'request-document:upload', 'request-document:download', 'notification:view')
WHERE r.code = 'REQUESTER' AND r.system_role;

-- Department head and committee member: approval capability plus read access to the case.
INSERT INTO role_permission (role_id, permission_id)
SELECT r.id, p.id
FROM role r
JOIN permission_definition p
    ON p.code IN ('approval:view', 'approval:act', 'request:view-own', 'request:view-scope',
                  'request-document:download', 'notification:view')
WHERE r.code IN ('DEPARTMENT_HEAD', 'COMMITTEE_MEMBER') AND r.system_role;

-- Recommending authority: reads the case and can act when the workflow assigns them.
INSERT INTO role_permission (role_id, permission_id)
SELECT r.id, p.id
FROM role r
JOIN permission_definition p
    ON p.code IN ('approval:view', 'approval:act', 'request:view-scope', 'request-document:download',
                  'notification:view')
WHERE r.code = 'RECOMMENDING_AUTHORITY' AND r.system_role;

