    updated_at     TIMESTAMPTZ  NOT NULL,
    updated_by     VARCHAR(64)  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0
);

-- Active names are unique WITHIN a category (BRD §8.6).
CREATE UNIQUE INDEX uk_expense_subcategory_active_name
    ON expense_subcategory (institution_id, category_id, lower(name)) WHERE active;
CREATE INDEX ix_expense_subcategory_category ON expense_subcategory (institution_id, category_id, active);

CREATE TABLE currency (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT       NOT NULL REFERENCES institution (id),
    code           VARCHAR(3)   NOT NULL,
    name           VARCHAR(100) NOT NULL,
    rate_to_base   NUMERIC(19, 4) NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL,
    created_by     VARCHAR(64)  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    updated_by     VARCHAR(64)  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_currency_code CHECK (code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_currency_rate CHECK (rate_to_base > 0),
    -- Four decimals maximum, enforced in the database as well: a direct import must not be
    -- able to create a rate the application cannot round-trip.
    CONSTRAINT ck_currency_rate_scale CHECK (rate_to_base = round(rate_to_base, 4))
);

CREATE UNIQUE INDEX uk_currency_institution_code ON currency (institution_id, code);
CREATE INDEX ix_currency_institution ON currency (institution_id, active);

