WHERE r.code = 'READ_ONLY' AND r.system_role;

-- Reference currency for the seeded institution so a request can be created immediately.
INSERT INTO currency (institution_id, code, name, rate_to_base, active, created_at, created_by, updated_at,
                      updated_by, version)
SELECT i.id, 'PKR', 'Pakistan Rupee', 1.0000, TRUE, CURRENT_TIMESTAMP, 'system', CURRENT_TIMESTAMP, 'system', 0
FROM institution i
WHERE NOT EXISTS (SELECT 1 FROM currency c WHERE c.institution_id = i.id AND c.code = 'PKR');
