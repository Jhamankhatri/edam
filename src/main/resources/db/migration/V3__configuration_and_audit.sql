CREATE TABLE committee_member (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id    BIGINT       NOT NULL REFERENCES institution (id),
    employee_id       VARCHAR(64)  NOT NULL,
    display_name      VARCHAR(200) NOT NULL,
    designation_label VARCHAR(120),
    designation       VARCHAR(32)  NOT NULL DEFAULT 'MEMBER',
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMPTZ  NOT NULL,
    created_by        VARCHAR(64)  NOT NULL,
    updated_at        TIMESTAMPTZ  NOT NULL,
    updated_by        VARCHAR(64)  NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_committee_member_designation
        CHECK (designation IN ('CEO', 'CFO', 'HEAD_OF_ADMIN_GSD', 'MEMBER'))
);

CREATE UNIQUE INDEX uk_committee_member_employee
    ON committee_member (institution_id, employee_id);

-- "Only one active CEO, CFO and Head of Admin & GSD" (BRD FM-08). Three partial unique
-- indexes, because a CHECK cannot express a per-group cardinality and a service check races.
CREATE UNIQUE INDEX uk_committee_member_single_ceo
    ON committee_member (institution_id) WHERE active AND designation = 'CEO';
CREATE UNIQUE INDEX uk_committee_member_single_cfo
    ON committee_member (institution_id) WHERE active AND designation = 'CFO';
CREATE UNIQUE INDEX uk_committee_member_single_hod
    ON committee_member (institution_id) WHERE active AND designation = 'HEAD_OF_ADMIN_GSD';

CREATE TABLE committee_level (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id        BIGINT         NOT NULL REFERENCES institution (id),
    name                  VARCHAR(120)   NOT NULL,
    amount_from           NUMERIC(19, 2) NOT NULL,
    amount_to             NUMERIC(19, 2),
    minimum_approvals     INTEGER        NOT NULL,
    required_member_count INTEGER        NOT NULL,
    requires_ceo          BOOLEAN        NOT NULL DEFAULT FALSE,
    requires_cfo          BOOLEAN        NOT NULL DEFAULT FALSE,
    active                BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ    NOT NULL,
    created_by            VARCHAR(64)    NOT NULL,
    updated_at            TIMESTAMPTZ    NOT NULL,
    updated_by            VARCHAR(64)    NOT NULL,
    version               BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_committee_level_band CHECK (amount_from >= 0 AND (amount_to IS NULL OR amount_to > amount_from)),
    CONSTRAINT ck_committee_level_min_approvals CHECK (minimum_approvals >= 1
        AND minimum_approvals <= required_member_count),
    CONSTRAINT ck_committee_level_members CHECK (required_member_count BETWEEN 1 AND 10)
);

CREATE UNIQUE INDEX uk_committee_level_active_name
    ON committee_level (institution_id, lower(name)) WHERE active;

-- Non-overlapping active EC amount ranges (BRD §8.6). Expressed as an exclusion constraint so
-- the database refuses an overlap even under concurrent administration; the service still
-- validates first to return a clear business message.
CREATE EXTENSION IF NOT EXISTS btree_gist;

ALTER TABLE committee_level
    ADD CONSTRAINT ex_committee_level_no_overlap
    EXCLUDE USING gist (
        institution_id WITH =,
        numrange(amount_from, COALESCE(amount_to, 'Infinity'), '[)') WITH &&
    ) WHERE (active);

CREATE TABLE committee_level_member (
    level_id  BIGINT NOT NULL REFERENCES committee_level (id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES committee_member (id),
    PRIMARY KEY (level_id, member_id)
);

CREATE TABLE delegation_rule (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id     BIGINT         NOT NULL REFERENCES institution (id),
    category_id        BIGINT         NOT NULL REFERENCES expense_category (id),
    subcategory_id     BIGINT         REFERENCES expense_subcategory (id),
    expense_nature     VARCHAR(8)     NOT NULL,
    committee_level_id BIGINT         REFERENCES committee_level (id),
    amount_from        NUMERIC(19, 2) NOT NULL DEFAULT 0,
    amount_to          NUMERIC(19, 2),
    active             BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ    NOT NULL,
    created_by         VARCHAR(64)    NOT NULL,
    updated_at         TIMESTAMPTZ    NOT NULL,
    updated_by         VARCHAR(64)    NOT NULL,
    version            BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_delegation_rule_nature CHECK (expense_nature IN ('OPEX', 'CAPEX')),
    CONSTRAINT ck_delegation_rule_band CHECK (amount_from >= 0 AND (amount_to IS NULL OR amount_to > amount_from))
);

-- "No duplicate active category/sub-category/nature rule" (BRD §8.6). NULLS NOT DISTINCT is
-- essential: without it PostgreSQL would allow unlimited category-wide (subcategory IS NULL)
-- duplicates, because NULL never equals NULL in a unique index.
CREATE UNIQUE INDEX uk_delegation_rule_active_classification
    ON delegation_rule (institution_id, category_id, subcategory_id, expense_nature) NULLS NOT DISTINCT
    WHERE active;

CREATE INDEX ix_delegation_rule_lookup
    ON delegation_rule (institution_id, expense_nature, category_id, active);

CREATE TABLE delegation_rule_approver (
    rule_id       BIGINT      NOT NULL REFERENCES delegation_rule (id) ON DELETE CASCADE,
    approver_type VARCHAR(32) NOT NULL,
    PRIMARY KEY (rule_id, approver_type),
    CONSTRAINT ck_delegation_rule_approver_type
        CHECK (approver_type IN ('DEPARTMENT_HEAD', 'RECOMMENDING_AUTHORITY', 'EXPENSE_COMMITTEE', 'CEO', 'CFO',
                                 'HEAD_OF_ADMIN_GSD'))
);

CREATE TABLE delegation_rule_authority (
    rule_id      BIGINT NOT NULL REFERENCES delegation_rule (id) ON DELETE CASCADE,
    authority_id BIGINT NOT NULL REFERENCES recommending_authority (id),
    PRIMARY KEY (rule_id, authority_id)
);

-- -------------------------------------------------------------------------------------
-- Audit trail (BRD AUD-01..03, §26)
--
-- Append-only. Immutability is enforced by trigger, not by convention: the BRD requires audit
-- records to be protected from ordinary application-user modification and deletion.
-- -------------------------------------------------------------------------------------

CREATE TABLE audit_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT,
    occurred_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor          VARCHAR(64) NOT NULL,
    actor_username VARCHAR(64),
    actor_roles    VARCHAR(500),
    action         VARCHAR(32) NOT NULL,
    resource_type  VARCHAR(64) NOT NULL,
    resource_id    VARCHAR(64),
    summary        VARCHAR(500),
    before_state   VARCHAR(8000),
    after_state    VARCHAR(8000),
    correlation_id VARCHAR(64),
    source_ip      VARCHAR(64)
);

CREATE INDEX ix_audit_event_institution_time ON audit_event (institution_id, occurred_at DESC);
CREATE INDEX ix_audit_event_resource ON audit_event (institution_id, resource_type, resource_id);
CREATE INDEX ix_audit_event_actor ON audit_event (institution_id, actor, occurred_at DESC);

COMMENT ON TABLE audit_event IS
    'Immutable audit trail. UPDATE and DELETE are rejected by trigger; retention is an open bank decision (OD-33).';

CREATE OR REPLACE FUNCTION edam_audit_event_is_append_only()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'audit_event is append-only: % is not permitted', TG_OP
        USING ERRCODE = 'insufficient_privilege';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_event_no_update
    BEFORE UPDATE ON audit_event
    FOR EACH ROW EXECUTE FUNCTION edam_audit_event_is_append_only();

CREATE TRIGGER trg_audit_event_no_delete
    BEFORE DELETE ON audit_event
    FOR EACH ROW EXECUTE FUNCTION edam_audit_event_is_append_only();

