-- =====================================================================================
-- EDAM Foundation — baseline schema (V1)
--
-- Scope discipline: this migration creates ONLY what the foundation genuinely needs.
-- OPEX, CAPEX, delegation matrix, Expense Committee, currency, workflow and audit tables
-- are intentionally NOT created here; they arrive with their own business phase and an
-- approved data model (BRD 8 / Delivery Phase 2+).
--
-- Conventions:
--   * snake_case identifiers, singular table names.
--   * Audit columns are mandatory and populated by JPA auditing.
--   * Money: NUMERIC(19,2). Rates: NUMERIC(19,6). Never floating point.
--   * Optimistic locking via a monotonically increasing version column.
-- =====================================================================================

CREATE TABLE institution (
    id                                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                                VARCHAR(32)  NOT NULL,
    name                                VARCHAR(200) NOT NULL,
    short_name                          VARCHAR(40)  NOT NULL,
    base_currency                       VARCHAR(3)   NOT NULL,
    primary_color                       VARCHAR(7),
    secondary_color                     VARCHAR(7),
    accent_color                        VARCHAR(7),
    language_tag                        VARCHAR(20)  NOT NULL,
    time_zone                           VARCHAR(40)  NOT NULL,
    department_head_limit               NUMERIC(19, 2),
    capex_department_restriction_enabled BOOLEAN     NOT NULL DEFAULT TRUE,
    active                              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at                          TIMESTAMPTZ  NOT NULL,
    created_by                          VARCHAR(64)  NOT NULL,
    updated_at                          TIMESTAMPTZ  NOT NULL,
    updated_by                          VARCHAR(64)  NOT NULL,
    version                             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_institution_code UNIQUE (code),
    CONSTRAINT ck_institution_code_format CHECK (code ~ '^[a-z0-9][a-z0-9-]{1,31}$'),
    CONSTRAINT ck_institution_base_currency CHECK (base_currency ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_institution_primary_color CHECK (primary_color IS NULL OR primary_color ~ '^#[0-9a-fA-F]{6}$'),
    CONSTRAINT ck_institution_secondary_color CHECK (secondary_color IS NULL OR secondary_color ~ '^#[0-9a-fA-F]{6}$'),
    CONSTRAINT ck_institution_accent_color CHECK (accent_color IS NULL OR accent_color ~ '^#[0-9a-fA-F]{6}$'),
    CONSTRAINT ck_institution_department_head_limit CHECK (department_head_limit IS NULL OR department_head_limit > 0)
);

COMMENT ON TABLE institution IS
    'Financial institution (tenant). Anchor of the multi-institution model; isolation strategy still open (BRD OD-20).';
COMMENT ON COLUMN institution.code IS 'Immutable tenant key used by configuration, logs and audit records.';
COMMENT ON COLUMN institution.department_head_limit IS
    'General delegation threshold in base currency; NULL means "not configured" and the platform fallback applies.';

-- Active institutions are looked up by code on every resolution; a partial index keeps
-- the common predicate fast without indexing retired tenants.
CREATE INDEX ix_institution_active ON institution (code) WHERE active;
