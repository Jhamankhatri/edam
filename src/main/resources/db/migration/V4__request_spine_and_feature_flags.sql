-- =====================================================================================
-- EDAM — feature flags, idempotency and workflow/request spine (V4)
--
-- V3 created the configuration plane and the access-control tables. This migration adds the
-- remaining tables the application layer needs before the request lifecycle can be built:
-- per-institution feature flags, durable idempotency keys, departments, and the expense
-- request aggregate with its workflow, approval and document tables.
--
-- Split from V3 rather than appended to it because V3 has already been applied in test
-- environments; a Flyway migration is immutable once released.
-- =====================================================================================

-- -------------------------------------------------------------------------------------
-- Institution feature flags (BRD INS-04)
--
-- Replaces the foundation's global flag (audit defect D-3). A row exists only when the
-- institution has expressed a preference, so "never decided" stays distinguishable from
-- "deliberately off".
-- -------------------------------------------------------------------------------------

CREATE TABLE institution_feature_flag (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT      NOT NULL REFERENCES institution (id),
    feature_key    VARCHAR(64) NOT NULL,
    enabled        BOOLEAN     NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    created_by     VARCHAR(64) NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    updated_by     VARCHAR(64) NOT NULL,
    version        BIGINT      NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uk_institution_feature_flag
    ON institution_feature_flag (institution_id, feature_key);

-- -------------------------------------------------------------------------------------
-- Migrate the foundation's GLOBAL CAPEX switch into the per-institution flag, then drop it.
--
-- The global column was audit defect D-3: one institution's deployment configuration changed
-- another's behaviour. The data is moved before the column is dropped, so no institution
-- loses a setting it had made. Rows are only created for institutions that had the column
-- set, preserving "never decided" as an absent row.
-- -------------------------------------------------------------------------------------

INSERT INTO institution_feature_flag (institution_id, feature_key, enabled, created_at, created_by,
                                      updated_at, updated_by, version)
SELECT i.id, 'CAPEX_DEPARTMENT_RESTRICTION', i.capex_department_restriction_enabled,
       CURRENT_TIMESTAMP, 'system', CURRENT_TIMESTAMP, 'system', 0
FROM institution i
WHERE i.capex_department_restriction_enabled IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM institution_feature_flag f
                  WHERE f.institution_id = i.id AND f.feature_key = 'CAPEX_DEPARTMENT_RESTRICTION');

ALTER TABLE institution DROP COLUMN capex_department_restriction_enabled;

-- -------------------------------------------------------------------------------------
-- Idempotency keys (BRD API-04)
--
-- Durable, not cached: a retried submit must not create a second request, and an evicted
-- cache would silently reopen that window. Only a key hash and a body fingerprint are
-- stored, never the body itself.
-- -------------------------------------------------------------------------------------

CREATE TABLE idempotency_record (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id      BIGINT      NOT NULL REFERENCES institution (id),
    key_hash            VARCHAR(64) NOT NULL,
    endpoint            VARCHAR(200) NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    response_status     INTEGER     NOT NULL,
    correlation_id      VARCHAR(64),
    created_at          TIMESTAMPTZ NOT NULL,
    expires_at          TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX uk_idempotency_record
    ON idempotency_record (institution_id, endpoint, key_hash);
CREATE INDEX ix_idempotency_record_expiry ON idempotency_record (expires_at);

-- -------------------------------------------------------------------------------------
-- Departments and branches (referenced by memberships, authorities and requests)
--
-- Identifiers rather than free text would need a source of truth, which BRD INT-01 leaves
-- to the bank's HR system. They are therefore configured here and referenced by code.
-- -------------------------------------------------------------------------------------

CREATE TABLE department (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT      NOT NULL REFERENCES institution (id),
    code           VARCHAR(64) NOT NULL,
    name           VARCHAR(200) NOT NULL,
    capex_eligible BOOLEAN     NOT NULL DEFAULT FALSE,
    active         BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL,
    created_by     VARCHAR(64) NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    updated_by     VARCHAR(64) NOT NULL,
    version        BIGINT      NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uk_department_code ON department (institution_id, code);

COMMENT ON COLUMN department.capex_eligible IS
    'When CAPEX department restriction is enabled, only eligible departments may raise CAPEX (BRD OD-21).';

-- -------------------------------------------------------------------------------------
-- Workflow definitions (BRD FM-01..FM-06)
--
-- Versioned and immutable once published. A submission pins the version it started under, so
-- publishing a new version never changes an in-flight request (BRD §8.6).
-- -------------------------------------------------------------------------------------

CREATE TABLE workflow_definition (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT      NOT NULL REFERENCES institution (id),
    code           VARCHAR(64) NOT NULL,
    name           VARCHAR(200) NOT NULL,
    description    VARCHAR(1000),
    created_at     TIMESTAMPTZ NOT NULL,
    created_by     VARCHAR(64) NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    updated_by     VARCHAR(64) NOT NULL,
    version        BIGINT      NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uk_workflow_definition_code ON workflow_definition (institution_id, code);

CREATE TABLE workflow_version (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id    BIGINT      NOT NULL REFERENCES institution (id),
    definition_id     BIGINT      NOT NULL REFERENCES workflow_definition (id),
    version_number    INTEGER     NOT NULL,
    status            VARCHAR(16) NOT NULL,
    definition_json   TEXT        NOT NULL,
    checksum          VARCHAR(64) NOT NULL,
    change_note       VARCHAR(1000),
    published_at      TIMESTAMPTZ,
    published_by      VARCHAR(64),
    created_at        TIMESTAMPTZ NOT NULL,
    created_by        VARCHAR(64) NOT NULL,
    updated_at        TIMESTAMPTZ NOT NULL,
    updated_by        VARCHAR(64) NOT NULL,
    version           BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_workflow_version_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'RETIRED')),
    CONSTRAINT ck_workflow_version_number CHECK (version_number >= 1)
);

CREATE UNIQUE INDEX uk_workflow_version_number
    ON workflow_version (definition_id, version_number);

-- At most one published version per definition, so "the current workflow" has exactly one
-- meaning. Enforced here because a service check would race with a concurrent publish.
CREATE UNIQUE INDEX uk_workflow_version_single_published
    ON workflow_version (definition_id) WHERE status = 'PUBLISHED';

-- -------------------------------------------------------------------------------------
-- Expense requests (BRD FM-01, FM-03, FM-05)
-- -------------------------------------------------------------------------------------

CREATE TABLE expense_request (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id         BIGINT         NOT NULL REFERENCES institution (id),
    request_number         VARCHAR(40)    NOT NULL,
    title                  VARCHAR(200)   NOT NULL,
    description            VARCHAR(4000),
    amount                 NUMERIC(19, 2) NOT NULL,
    currency_code          VARCHAR(3)     NOT NULL,
    amount_in_base         NUMERIC(19, 2) NOT NULL,
    expense_nature         VARCHAR(8)     NOT NULL,
    category_id            BIGINT         NOT NULL REFERENCES expense_category (id),
    subcategory_id         BIGINT         REFERENCES expense_subcategory (id),
    department_code        VARCHAR(64)    NOT NULL,
    branch_code            VARCHAR(64),
    requester_employee_id  VARCHAR(64)    NOT NULL,
    requester_username     VARCHAR(64)    NOT NULL,
    requester_display_name VARCHAR(200),
    state                  VARCHAR(32)    NOT NULL,
    workflow_definition_id BIGINT         REFERENCES workflow_definition (id),
    workflow_version_id    BIGINT         REFERENCES workflow_version (id),
    current_step_code      VARCHAR(64),
    submitted_at           TIMESTAMPTZ,
    finalized_at           TIMESTAMPTZ,
    cancellation_reason    VARCHAR(1000),
    created_at             TIMESTAMPTZ    NOT NULL,
    created_by             VARCHAR(64)    NOT NULL,
    updated_at             TIMESTAMPTZ    NOT NULL,
    updated_by             VARCHAR(64)    NOT NULL,
    version                BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_expense_request_amount CHECK (amount > 0),
    CONSTRAINT ck_expense_request_amount_scale CHECK (amount = round(amount, 2)),
    CONSTRAINT ck_expense_request_amount_base CHECK (amount_in_base >= 0),
    CONSTRAINT ck_expense_request_nature CHECK (expense_nature IN ('OPEX', 'CAPEX')),
    CONSTRAINT ck_expense_request_currency CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_expense_request_state CHECK (state IN ('DRAFT', 'SUBMITTED', 'IN_APPROVAL', 'RETURNED',
        'APPROVED', 'REJECTED', 'CANCELLED', 'REVERSED'))
);

CREATE UNIQUE INDEX uk_expense_request_number ON expense_request (institution_id, request_number);
CREATE INDEX ix_expense_request_requester
    ON expense_request (institution_id, requester_employee_id, created_at DESC);
CREATE INDEX ix_expense_request_state ON expense_request (institution_id, state, created_at DESC);
CREATE INDEX ix_expense_request_department
    ON expense_request (institution_id, department_code, created_at DESC);

COMMENT ON COLUMN expense_request.workflow_version_id IS
    'Pinned at submission. Publishing a new workflow version never changes an in-flight request (BRD §8.6).';
COMMENT ON COLUMN expense_request.amount_in_base IS
    'Amount converted at the rate recorded on the request. Conversion policy and rounding are an open bank decision (OD-31).';

-- Currency rate snapshots: a request records the rate it was created with, so a later rate
-- change cannot retroactively alter the approved amount.
CREATE TABLE expense_request_currency_snapshot (
    request_id     BIGINT      NOT NULL REFERENCES expense_request (id) ON DELETE CASCADE,
    institution_id BIGINT      NOT NULL REFERENCES institution (id),
    currency_code  VARCHAR(3)  NOT NULL,
    rate_to_base   NUMERIC(19, 4) NOT NULL,
    captured_at    TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (request_id, currency_code)
);

-- -------------------------------------------------------------------------------------
-- Approval tasks (BRD §8.4, §8.5)
-- -------------------------------------------------------------------------------------

CREATE TABLE approval_task (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id      BIGINT       NOT NULL REFERENCES institution (id),
    request_id          BIGINT       NOT NULL REFERENCES expense_request (id),
    step_code           VARCHAR(64)  NOT NULL,
    step_label          VARCHAR(200),
    required_permission VARCHAR(80),
    approver_role       VARCHAR(64)  NOT NULL,
    assigned_employee_id VARCHAR(64),
    assigned_department VARCHAR(64),
    sequence_number     INTEGER      NOT NULL,
    status              VARCHAR(16)  NOT NULL,
    acted_by_employee_id VARCHAR(64),
    acted_by_username   VARCHAR(64),
    acted_at            TIMESTAMPTZ,
    decision_comment    VARCHAR(2000),
    forward_to_employee_id VARCHAR(64),
    created_at          TIMESTAMPTZ  NOT NULL,
    created_by          VARCHAR(64)  NOT NULL,
    updated_at          TIMESTAMPTZ  NOT NULL,
    updated_by          VARCHAR(64)  NOT NULL,
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_approval_task_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REVERTED', 'FORWARDED', 'CANCELLED', 'SKIPPED'))
);

CREATE INDEX ix_approval_task_request ON approval_task (institution_id, request_id, sequence_number);
CREATE INDEX ix_approval_task_inbox
    ON approval_task (institution_id, status, assigned_employee_id, created_at DESC);
CREATE INDEX ix_approval_task_department
    ON approval_task (institution_id, status, assigned_department, created_at DESC);

-- A request may only have one open task at a given step and sequence, which is what prevents
-- a double-approve from a retried request.
CREATE UNIQUE INDEX uk_approval_task_open_step
    ON approval_task (request_id, sequence_number) WHERE status = 'PENDING';

-- -------------------------------------------------------------------------------------
-- Request history (who acted, when, on which version) — the case file an auditor reads
-- -------------------------------------------------------------------------------------

CREATE TABLE request_history_entry (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT       NOT NULL REFERENCES institution (id),
    request_id     BIGINT       NOT NULL REFERENCES expense_request (id),
    sequence_number INTEGER     NOT NULL,
    action         VARCHAR(32)  NOT NULL,
    from_state     VARCHAR(32),
    to_state       VARCHAR(32),
    actor_employee_id VARCHAR(64),
    actor_username VARCHAR(64),
    comment        VARCHAR(2000),
    occurred_at    TIMESTAMPTZ  NOT NULL,
    correlation_id VARCHAR(64)
);

CREATE INDEX ix_request_history_request
    ON request_history_entry (institution_id, request_id, sequence_number);

-- -------------------------------------------------------------------------------------
-- Documents (BRD DOC-01..04) — metadata only; binaries live in Cloudinary
-- -------------------------------------------------------------------------------------

CREATE TABLE document (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id   BIGINT       NOT NULL REFERENCES institution (id),
    request_id       BIGINT       REFERENCES expense_request (id),
    original_filename VARCHAR(255) NOT NULL,
    storage_provider VARCHAR(32)  NOT NULL,
    public_id        VARCHAR(255) NOT NULL,
    resource_type    VARCHAR(32),
    format           VARCHAR(32),
    bytes            BIGINT       NOT NULL,
    content_type     VARCHAR(150),
    checksum_sha256  VARCHAR(64),
    uploaded_by      VARCHAR(64)  NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL,
    created_by       VARCHAR(64)  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    updated_by       VARCHAR(64)  NOT NULL,
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_document_provider CHECK (storage_provider IN ('CLOUDINARY', 'LOCAL')),
    CONSTRAINT ck_document_bytes CHECK (bytes > 0)
);

CREATE INDEX ix_document_request ON document (institution_id, request_id);
CREATE UNIQUE INDEX uk_document_public_id ON document (institution_id, storage_provider, public_id);

COMMENT ON COLUMN document.public_id IS
    'Provider-side identifier (Cloudinary public_id). No credential or signed URL is stored here.';
